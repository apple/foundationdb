#!/usr/bin/env python3
"""
Generate test files for benchmarking a cluster's storage engine with the YCSB workload, plus interference tests that
run YCSB while the cluster absorbs a large clear or moves data off an excluded storage process. The storage engine is
whatever the cluster is configured with, so the same tests compare engines across clusters.

For each layout this writes:
  YCSBClusterBench_{size}_Setup_{layout}.toml        load the layout's dataset
  YCSBClusterBench_{size}_Throughput_{layout}.toml   per (distribution, threads): bounce, warmup, measured at unlimited
                                                     tps, to find where throughput saturates
With --latency-tps and --latency-threads (a non-saturating rate chosen from a throughput run), also:
  YCSBClusterBench_{size}_Latency_{layout}.toml           per distribution: bounce, warmup, measured at the fixed rate
  YCSBClusterBench_{size}_LargeClearSetup_{layout}.toml   load a second copy of the dataset
  YCSBClusterBench_{size}_LargeClear_{layout}.toml        YCSB at the fixed rate while the second copy is cleared
and with --exclude-port as well:
  YCSBClusterBench_{size}_DataMovement_{layout}.toml      YCSB at the fixed rate while the storage process on that
                                                          port is excluded, so its data moves to the remaining ones
Each measured phase restarts every non-tester process first (the bounce) so it starts with cold caches.

YCSBClusterBench_{size}_Cluster_{layout}.txt lists the setup, throughput, latency, and large clear tests in run order
for one cluster; YCSBClusterBench_{size}_DataMovement_{layout}.txt lists the setup and data movement tests for a
cluster with an extra storage process on the excluded port. Each layout's dataset has its own nodePrefix, so both
layouts' lists can run on the same cluster.

Usage:
  gen_cluster_bench.py --out-dir DIR [--size {1g,10g,100g}] [--test-duration S]
      [--latency-tps N --latency-threads M [--exclude-port PORT]]
"""

import argparse
import os

ROW_BYTES = 1024

SIZE_NODE_COUNTS = {
    "1g": 1_000_000,
    "10g": 10_000_000,
    "100g": 100_000_000,
}

# nodePrefix of each layout's dataset, and of its second copy for the large clear
LAYOUTS = {
    "single_cf": {"variant": "singleCF", "nodePrefix": 1, "clearNodePrefix": 3},
    "multi_cf": {"variant": "multiCF", "nodePrefix": 2, "clearNodePrefix": 4},
}
# A nodePrefix takes up the first 16 bytes of a key
KEY_BYTES = 32

READ_WEIGHT = 80
UPDATE_WEIGHT = 20
LATENCY_WINDOW = 5.0

# Setup and warmup concurrency
SETUP_THREADS = 128
WARMUP_TPS = 5000
WARMUP_DURATION = 180.0
TEST_DURATION = 300.0
BOUNCE_DURATION = 120.0
# Off simulation Attrition restarts this many non-tester processes, one after another, which is all of them
BOUNCE_WORKERS = 100000

# Throughput ramps total client threads across all testers at unlimited tps
THROUGHPUT_THREAD_LEVELS = [1, 2, 4, 8, 16, 32, 64, 128, 256]

# The interference event happens this long into the measured phase, which keeps going this long after it, so slow
# reclaims and data moves can be seen to finish
EVENT_DELAY = 150.0
POST_EVENT_DURATION = 1800.0
INTERFERENCE_DURATION = EVENT_DELAY + POST_EVENT_DURATION

DISTRIBUTIONS = {
    "uniform": "random",
    "zipfian": "zipfian",
}

HEADER = """\
# WARNING: this file is auto-generated by contrib/ycsb_bench/gen_cluster_bench.py
# Any edits should be made via script modifications.
"""


# Failure injection workloads are for simulation; against a real cluster, Attrition suspends processes indefinitely
def test_header(title, timeout, wait_for_quiescence_end=True):
    return f"""\
[[test]]
testTitle = '{title}'
clearAfterTest = false
waitForQuiescenceBegin = false
waitForQuiescenceEnd = {'true' if wait_for_quiescence_end else 'false'}
runConsistencyCheck = false
runFailureWorkloads = false
runSetup = false
databasePingDelay = 0.0
timeout = {timeout}

"""


def dataset_fields(layout, node_count, node_prefix):
    return f"""\
    nodeCount = {node_count}
    nodePrefix = {node_prefix}
    keyBytes = {KEY_BYTES}
    valueBytes = {ROW_BYTES}
    variant = '{LAYOUTS[layout]["variant"]}'
"""


def ycsb_workload(
    layout, node_count, duration, threads, dist, tps, read_weight=READ_WEIGHT
):
    return f"""\
    [[test.workload]]
    testName = 'YCSB'
    testDuration = {duration:.1f}
    threads = {threads}
{dataset_fields(layout, node_count, LAYOUTS[layout]["nodePrefix"])}\
    distribution = '{dist}'
    tps = {tps}
    readWeight = {read_weight}
    updateWeight = {100 - read_weight}
    latencyWindowSeconds = {LATENCY_WINDOW}
"""


def bounce_block(tag):
    return f"""\
{test_header(f"Bounce_{tag}", 20000, wait_for_quiescence_end=False)}\
    [[test.workload]]
    testName = 'Attrition'
    testDuration = {BOUNCE_DURATION:.1f}
    reboot = true
    liveDuration = 0.0
    suspendDuration = 0.0
    workersToKill = {BOUNCE_WORKERS}
    workersToLeave = 0

"""


def warmup_block(tag, layout, node_count):
    return f"""\
{test_header(f"Warmup_{tag}", 400, wait_for_quiescence_end=False)}\
{ycsb_workload(layout, node_count, WARMUP_DURATION, SETUP_THREADS, "random", WARMUP_TPS, read_weight=100)}
"""


def setup_toml(size, layout, node_count, workload, node_prefix, title):
    load_only = {
        "YCSB": "    testDuration = 0.0",
        "ConcurrentClearRange": "    clear = false",
    }
    return f"""\
{HEADER}
# Load {node_count:,} rows under nodePrefix {node_prefix}.

[[test]]
testTitle = '{title}'
clearAfterTest = false
waitForQuiescenceBegin = false
waitForQuiescenceEnd = true
runConsistencyCheck = false
runFailureWorkloads = false
databasePingDelay = 0.0
timeout = 20000

    [[test.workload]]
    testName = '{workload}'
{load_only[workload]}
{dataset_fields(layout, node_count, node_prefix)}"""


def ramp_toml(kind, description, size, layout, node_count, levels, test_duration):
    """levels is a list of (title_suffix, threads, tps); each gets bounce, warmup, and measured per distribution."""
    blocks = [
        f"""\
{HEADER}
# {kind} YCSB for {layout} at {size}: {description}.
# Per (distribution, level): bounce, read-only warmup, then the {READ_WEIGHT}/{UPDATE_WEIGHT} measured run.
# Requires the dataset loaded by YCSBClusterBench_{size}_Setup_{layout}.toml.

"""
    ]
    for dist_key, dist in DISTRIBUTIONS.items():
        for title_suffix, threads, tps in levels:
            tag = f"{kind}_{dist_key}_{title_suffix}"
            blocks.append(bounce_block(tag))
            blocks.append(warmup_block(tag, layout, node_count))
            blocks.append(
                test_header(
                    f"{kind}_{layout}_{dist_key}_{title_suffix}",
                    int(test_duration) + 300,
                )
            )
            blocks.append(
                ycsb_workload(layout, node_count, test_duration, threads, dist, tps)
            )
            blocks.append("\n")
    return "".join(blocks)


def large_clear_toml(size, layout, node_count, latency):
    return f"""\
{HEADER}
# Large clear for {layout} at {size}: YCSB at a fixed rate while a single clear of a second copy of the dataset
# commits {EVENT_DELAY:.0f}s in, then for {POST_EVENT_DURATION:.0f}s more while the storage engine reclaims it.
# Requires YCSBClusterBench_{size}_Setup_{layout}.toml and YCSBClusterBench_{size}_LargeClearSetup_{layout}.toml.

{bounce_block(f"LargeClear_{layout}")}\
{test_header(f"LargeClear_{size}_{layout}", int(INTERFERENCE_DURATION) + 300)}\
{ycsb_workload(layout, node_count, INTERFERENCE_DURATION, latency["threads"], "random", latency["tps"])}
    [[test.workload]]
    testName = 'ConcurrentClearRange'
{dataset_fields(layout, node_count, LAYOUTS[layout]["clearNodePrefix"])}\
    clearDelay = {EVENT_DELAY:.1f}
"""


def data_movement_toml(size, layout, node_count, latency, exclude_port):
    # Not waiting for quiescence afterwards, since a slow move would still be running and is measured during the test
    return f"""\
{HEADER}
# Data movement for {layout} at {size}: YCSB at a fixed rate while the storage process on port {exclude_port} is
# excluded {EVENT_DELAY:.0f}s in, then for {POST_EVENT_DURATION:.0f}s more while its data moves to the remaining ones.
# Requires YCSBClusterBench_{size}_Setup_{layout}.toml.

{bounce_block(f"DataMovement_{layout}")}\
{test_header(f"DataMovement_{size}_{layout}", int(INTERFERENCE_DURATION) + 300, wait_for_quiescence_end=False)}\
{ycsb_workload(layout, node_count, INTERFERENCE_DURATION, latency["threads"], "random", latency["tps"])}
    [[test.workload]]
    testName = 'ExcludeProcesses'
    ports = '{exclude_port}'
    excludeDelay = {EVENT_DELAY:.1f}
"""


def write(path, content):
    with open(path, "w") as f:
        f.write(content)
    print(f"  wrote {path}")


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--size", choices=list(SIZE_NODE_COUNTS), default="10g")
    parser.add_argument(
        "--test-duration",
        type=float,
        default=TEST_DURATION,
        help="seconds per measured throughput and latency test",
    )
    parser.add_argument(
        "--latency-tps", type=int, help="tps for latency and interference tests"
    )
    parser.add_argument(
        "--latency-threads",
        type=int,
        help="total threads for latency and interference tests",
    )
    parser.add_argument(
        "--exclude-port",
        type=int,
        help="port of the storage process the data movement test excludes",
    )
    args = parser.parse_args()
    if args.test_duration <= 0:
        parser.error("--test-duration must be positive")
    if (args.latency_tps is None) != (args.latency_threads is None):
        parser.error("--latency-tps and --latency-threads must be given together")
    if args.latency_tps is not None and (
        args.latency_tps <= 0 or args.latency_threads <= 0
    ):
        parser.error("--latency-tps and --latency-threads must be positive")
    if args.exclude_port is not None and args.latency_tps is None:
        parser.error("--exclude-port needs --latency-tps and --latency-threads")
    latency = (
        None
        if args.latency_tps is None
        else {"tps": args.latency_tps, "threads": args.latency_threads}
    )

    size = args.size
    node_count = SIZE_NODE_COUNTS[size]
    os.makedirs(args.out_dir, exist_ok=True)
    for layout, spec in LAYOUTS.items():
        files = {
            f"YCSBClusterBench_{size}_Setup_{layout}.toml": setup_toml(
                size, layout, node_count, "YCSB", spec["nodePrefix"], f"Setup_{layout}"
            ),
            f"YCSBClusterBench_{size}_Throughput_{layout}.toml": ramp_toml(
                "Throughput",
                "ramp total client threads at unlimited tps",
                size,
                layout,
                node_count,
                [(f"threads{n}", n, 0) for n in THROUGHPUT_THREAD_LEVELS],
                args.test_duration,
            ),
        }
        cluster_order = list(files)
        if latency is not None:
            interference = {
                f"YCSBClusterBench_{size}_Latency_{layout}.toml": ramp_toml(
                    "Latency",
                    "a fixed non-saturating rate",
                    size,
                    layout,
                    node_count,
                    [
                        (
                            f"tps{latency['tps']}_threads{latency['threads']}",
                            latency["threads"],
                            latency["tps"],
                        )
                    ],
                    args.test_duration,
                ),
                f"YCSBClusterBench_{size}_LargeClearSetup_{layout}.toml": setup_toml(
                    size,
                    layout,
                    node_count,
                    "ConcurrentClearRange",
                    spec["clearNodePrefix"],
                    f"LargeClearSetup_{layout}",
                ),
                f"YCSBClusterBench_{size}_LargeClear_{layout}.toml": large_clear_toml(
                    size, layout, node_count, latency
                ),
            }
            files.update(interference)
            cluster_order += list(interference)
        if args.exclude_port is not None:
            name = f"YCSBClusterBench_{size}_DataMovement_{layout}.toml"
            files[name] = data_movement_toml(
                size, layout, node_count, latency, args.exclude_port
            )
            write(
                os.path.join(
                    args.out_dir, f"YCSBClusterBench_{size}_DataMovement_{layout}.txt"
                ),
                f"YCSBClusterBench_{size}_Setup_{layout}.toml\n{name}\n",
            )
        for name, content in files.items():
            write(os.path.join(args.out_dir, name), content)
        write(
            os.path.join(args.out_dir, f"YCSBClusterBench_{size}_Cluster_{layout}.txt"),
            "\n".join(cluster_order) + "\n",
        )


if __name__ == "__main__":
    main()
