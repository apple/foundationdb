#!/usr/bin/env python3
"""
Generate test files for benchmarking storage engines directly with the YCSBKVStore workload, which runs YCSB against a
single storage engine instance inside a tester process.

For each engine, layout, and load method this writes:
  - Load:       KVStoreBench_{size}_Load_{engine}_{layout}_{method}.toml
      loads the store with testDuration=0 and exits, so later tests can reuse it
  - Throughput: KVStoreBench_{size}_Throughput_{engine}_{layout}_{method}_{dist}_{cache_pct}pct.toml
      one [[test]] per actor count at unlimited tps, to find where throughput saturates
  - Latency:    KVStoreBench_{size}_Latency_{engine}_{layout}_{method}_{dist}_{cache_pct}pct.toml
      a fixed non-saturating tps and actor count; only with --latency-tps/--latency-actors, which are chosen from a
      throughput run
All reads are read-only, start cold (dropCaches), and reuse the loaded store (skipLoad). For each (engine, cache_pct)
it also writes KVStoreBench_{size}_{engine}_{cache_pct}pct.txt, the run order of the tests above: each load followed by
the reads of what it loaded. Run each list in order against one tester process, since a load replaces the previous
store for that engine.

Load methods:
  seq_quiesce        sequential key order, then vacuum() to finish the engine's deferred work
  random_quiesce     random key order, then vacuum()
  random_no_quiesce  random key order, leaving deferred work (Redwood's remap queue, RocksDB compaction) unfinished;
                     reads then see the store as the load left it
SQLite has no deferred work after an insert-only load, so it only runs the quiesce methods.

Cache size is pct% of the logical dataset. Redwood and RocksDB caches are set per store by the workload. SQLite uses
the tester process's page cache, so run its lists on a tester started with --cache-memory set to the listed size.

Usage:
  gen_kvstore_bench.py --out-dir DIR [--size {1g,10g,100g}] [--engines redwood,sqlite,rocksdb]
      [--cache-pcts 1,10,100] [--data-dir DIR] [--test-duration S] [--latency-tps N --latency-actors M]
"""

import argparse
import os

ROW_BYTES = (
    1024  # a single_cf row is one 1KB value, a multi_cf row ten ~100 byte values
)

SIZE_NODE_COUNTS = {
    "1g": 1_000_000,
    "10g": 10_000_000,
    "100g": 100_000_000,
}

DEFAULT_CACHE_PCTS = [1, 10, 100]

# Commit every 10MB during loads
LOAD_BATCH_BYTES = 10_000_000

# The default test timeout is far short of a large random order load
LOAD_TIMEOUT = 86400

TEST_DURATION = 300.0

# Throughput ramps concurrency at unlimited tps
THROUGHPUT_ACTOR_LEVELS = [1, 2, 4, 8, 16, 32, 64, 128, 256]

MIB = 1 << 20

ENGINES = {
    "redwood": {
        "storeType": "ssd-redwood-1",
        "ext": ".redwood-v1",
        "methods": ["seq_quiesce", "random_quiesce", "random_no_quiesce"],
    },
    "sqlite": {
        "storeType": "ssd-2",
        "ext": ".sqlite",
        "methods": ["seq_quiesce", "random_quiesce"],
    },
    # RocksDB compacts in the background even without writes, so reads pause it to see the layout the load left
    "rocksdb": {
        "storeType": "ssd-rocksdb-v1",
        "ext": ".rocksdb",
        "methods": ["seq_quiesce", "random_quiesce", "random_no_quiesce"],
        "pauseBackgroundWork": True,
    },
}

LAYOUTS = {
    "single_cf": {"variant": "singleCF", "fieldCount": 1},
    "multi_cf": {"variant": "multiCF", "fieldCount": 10},
}

# (loadOrder, vacuum)
METHODS = {
    "seq_quiesce": ("sequential", True),
    "random_quiesce": ("random", True),
    "random_no_quiesce": ("random", False),
}

DISTRIBUTIONS = {
    "uniform": "random",
    "zipfian": "zipfian",
}

HEADER = """\
# WARNING: this file is auto-generated by contrib/ycsb_bench/gen_kvstore_bench.py
# Any edits should be made via script modifications.
"""


def cache_bytes(pct, logical_bytes):
    # Whole MiB, so --cache-memory (in MiB) can match it exactly
    return max(MIB, logical_bytes * pct // 100 // MIB * MIB)


def store_path(data_dir, size, engine):
    # One store per engine: each load replaces the previous one, so a host only ever holds one dataset. Reads of the
    # wrong (layout, method) fail the workload's check of the reused store rather than silently using it.
    return os.path.join(
        data_dir, f"kvstore-bench-{size}-{engine}{ENGINES[engine]['ext']}"
    )


def workload_lines(fields):
    lines = []
    for k, v in fields.items():
        if isinstance(v, bool):
            v = "true" if v else "false"
        elif isinstance(v, str):
            v = f"'{v}'"
        elif isinstance(v, float):
            v = f"{v:.1f}"
        lines.append(f"    {k} = {v}")
    return "\n".join(lines)


def common_fields(engine, layout, node_count):
    return {
        "testName": "YCSBKVStore",
        "nodeCount": node_count,
        "valueBytes": ROW_BYTES,
        "fieldCount": LAYOUTS[layout]["fieldCount"],
        "variant": LAYOUTS[layout]["variant"],
        "storeType": ENGINES[engine]["storeType"],
    }


def load_toml(size, engine, layout, method, node_count, data_dir):
    load_order, vacuum = METHODS[method]
    fields = common_fields(engine, layout, node_count)
    fields.update(
        {
            "loadOrder": load_order,
            "loadBatchBytes": LOAD_BATCH_BYTES,
            "vacuum": vacuum,
            "testDuration": 0.0,
            "filename": store_path(data_dir, size, engine),
        }
    )
    return f"""\
{HEADER}
# Load {node_count:,} rows into {engine} / {layout} in {load_order} key order{', then vacuum' if vacuum else ''}.

[[test]]
testTitle = 'Load_{size}_{engine}_{layout}_{method}'
useDB = false
startDelay = 0
timeout = {LOAD_TIMEOUT}

    [[test.workload]]
{workload_lines(fields)}
"""


def read_toml(
    kind,
    size,
    engine,
    layout,
    method,
    dist,
    pct,
    node_count,
    data_dir,
    levels,
    test_duration,
):
    """levels is a list of (title_suffix, tps, num_actors), one [[test]] each."""
    cache = cache_bytes(pct, node_count * ROW_BYTES)
    blocks = []
    for title_suffix, tps, num_actors in levels:
        fields = common_fields(engine, layout, node_count)
        fields.update(
            {
                "distribution": DISTRIBUTIONS[dist],
                "skipLoad": True,
                "filename": store_path(data_dir, size, engine),
                "pageCacheBytes": cache,
                "dropCaches": True,
                "numActors": num_actors,
                "tps": tps,
                "testDuration": test_duration,
                "readWeight": 100,
                "updateWeight": 0,
            }
        )
        if ENGINES[engine].get("pauseBackgroundWork"):
            fields["pauseBackgroundWork"] = True
        blocks.append(
            f"""\
[[test]]
testTitle = '{kind}_{size}_{engine}_{layout}_{method}_{dist}_{pct}pct_{title_suffix}'
useDB = false
startDelay = 0

    [[test.workload]]
{workload_lines(fields)}
"""
        )
    sqlite_note = (
        f"# The tester must run with --cache-memory {cache // MIB}MiB, which pageCacheBytes must match.\n"
        if engine == "sqlite"
        else ""
    )
    return f"""\
{HEADER}
# {kind} reads of {engine} / {layout} / {method}, {dist} distribution, cache {pct}% of the dataset.
# Reuses the store from KVStoreBench_{size}_Load_{engine}_{layout}_{method}.toml.
{sqlite_note}
{chr(10).join(blocks)}"""


def write(path, content):
    with open(path, "w") as f:
        f.write(content)
    print(f"  wrote {path}")


def comma_list(convert):
    def parse(value):
        items = [convert(v) for v in value.split(",") if v]
        if not items or len(set(items)) != len(items):
            raise argparse.ArgumentTypeError(f"invalid list: {value}")
        return items

    return parse


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--size", choices=list(SIZE_NODE_COUNTS), default="10g")
    parser.add_argument("--engines", type=comma_list(str), default=list(ENGINES))
    parser.add_argument(
        "--cache-pcts", type=comma_list(int), default=DEFAULT_CACHE_PCTS
    )
    parser.add_argument(
        "--data-dir",
        default=".",
        help="where the tester keeps the store files (default: its working dir)",
    )
    parser.add_argument(
        "--test-duration",
        type=float,
        default=TEST_DURATION,
        help="seconds per read [[test]]",
    )
    parser.add_argument(
        "--latency-tps",
        type=int,
        help="tps for latency tests, which are skipped without it",
    )
    parser.add_argument(
        "--latency-actors",
        type=int,
        help="actors for latency tests, required with --latency-tps",
    )
    args = parser.parse_args()

    for engine in args.engines:
        if engine not in ENGINES:
            parser.error(f"unknown engine {engine!r}; choose from {', '.join(ENGINES)}")
    if any(p <= 0 or p > 100 for p in args.cache_pcts):
        parser.error("--cache-pcts must be in (0, 100]")
    if args.test_duration <= 0:
        parser.error("--test-duration must be positive")
    if (args.latency_tps is None) != (args.latency_actors is None):
        parser.error("--latency-tps and --latency-actors must be given together")
    if args.latency_tps is not None and (
        args.latency_tps <= 0 or args.latency_actors <= 0
    ):
        parser.error("--latency-tps and --latency-actors must be positive")

    node_count = SIZE_NODE_COUNTS[args.size]
    kinds = {"Throughput": [(f"actors{n}", 0, n) for n in THROUGHPUT_ACTOR_LEVELS]}
    if args.latency_tps is not None:
        kinds["Latency"] = [
            (
                f"tps{args.latency_tps}_actors{args.latency_actors}",
                args.latency_tps,
                args.latency_actors,
            )
        ]

    os.makedirs(args.out_dir, exist_ok=True)
    for engine in args.engines:
        order = {pct: [] for pct in args.cache_pcts}
        for layout in LAYOUTS:
            for method in ENGINES[engine]["methods"]:
                name = f"KVStoreBench_{args.size}_Load_{engine}_{layout}_{method}.toml"
                write(
                    os.path.join(args.out_dir, name),
                    load_toml(
                        args.size, engine, layout, method, node_count, args.data_dir
                    ),
                )
                for pct in args.cache_pcts:
                    order[pct].append(name)
                for kind, levels in kinds.items():
                    for dist in DISTRIBUTIONS:
                        for pct in args.cache_pcts:
                            name = f"KVStoreBench_{args.size}_{kind}_{engine}_{layout}_{method}_{dist}_{pct}pct.toml"
                            content = read_toml(
                                kind,
                                args.size,
                                engine,
                                layout,
                                method,
                                dist,
                                pct,
                                node_count,
                                args.data_dir,
                                levels,
                                args.test_duration,
                            )
                            write(os.path.join(args.out_dir, name), content)
                            order[pct].append(name)
        for pct, names in order.items():
            write(
                os.path.join(
                    args.out_dir, f"KVStoreBench_{args.size}_{engine}_{pct}pct.txt"
                ),
                "\n".join(names) + "\n",
            )


if __name__ == "__main__":
    main()
